def guide_list():
    """The guides in guides/index.json that have a guide.md: [{slug, title, summary, group, order}], by group then
    order, each with cover {palette, figure} (only the parts that check out: one of GUIDE_PALETTES, a figure file the
    guide has), related (slugs of other listed guides) and minutes (a whole number, 1 to 600) when the index gives
    them. An index that is missing, unreadable, over MAX_GUIDE_INDEX bytes or not a list gives []; entries with a bad
    slug are left out. An entry marked "upgrade": true whose guide.md is not on disk (a copy that ships only the free
    guides) is kept with absent: true, so the shelf, links and the Help now tree reach its locked preview."""
    try:
        with open(os.path.join(GUIDES_DIR, "index.json"), "rb") as f:
            raw = f.read(MAX_GUIDE_INDEX + 1)
        if len(raw) > MAX_GUIDE_INDEX:  # too big to be a list of guides: none are shown
            return []
        entries = json.loads(raw.decode("utf-8"))
    except (OSError, ValueError):
        return []
    if not isinstance(entries, list):
        return []
    out, seen = [], set()
    for e in entries:
        if not isinstance(e, dict):
            continue
        slug = e.get("slug")
        if not isinstance(slug, str) or not GUIDE_SLUG.fullmatch(slug) or slug in seen:
            continue
        absent = not guide_file(slug, "guide.md")
        if absent and (e.get("upgrade") is not True or slug in upgrade.FREE_GUIDES):
            continue
        seen.add(slug)
        order = e.get("order")
        out.append({"slug": slug, "title": str(e.get("title") or slug)[:200], "summary": str(e.get("summary") or "")[:600],
                    "group": str(e.get("group") or "Other")[:100],
                    "order": order if isinstance(order, (int, float)) and not isinstance(order, bool) else 0})
        if absent:
            out[-1]["absent"] = True
        cover = e.get("cover")
        if isinstance(cover, dict):
            c = {}
            if cover.get("palette") in GUIDE_PALETTES:
                c["palette"] = cover["palette"]
            fig = cover.get("figure")
            if isinstance(fig, str) and GUIDE_FIGURE.fullmatch(fig) and guide_file(slug, fig):
                c["figure"] = fig
            if c:
                out[-1]["cover"] = c
        minutes = e.get("minutes")
        if isinstance(minutes, int) and not isinstance(minutes, bool) and 1 <= minutes <= 600:
            out[-1]["minutes"] = minutes
        related = e.get("related")
        if isinstance(related, list):
            out[-1]["related"] = [r for r in related[:20] if isinstance(r, str) and GUIDE_SLUG.fullmatch(r) and r != slug]
    listed = {g["slug"] for g in out}
    for g in out:  # a related guide that isn't listed is left out
        if "related" in g:
            g["related"] = list(dict.fromkeys(r for r in g["related"] if r in listed))
    out.sort(key=lambda g: (g["group"].lower(), g["order"], g["title"].lower()))
    return out


