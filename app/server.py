def quick_results(lib, question):
    """The library search with the question as typed (Documents only, and the panel's first list before the model
    searches): [{id, title, source, official}], at most 8. A failing search gives []: the answer goes on without it."""
    if lib is None:
        return []
    try:
        hits = lib.search(question[:MAX_QUERY], limit=8)
    except Exception as exc:  # noqa: BLE001 - a damaged index must not stop the answer
        print(f"The quick search failed: {exc}", file=sys.stderr)
        return []
    return [{k: h[k] for k in ("id", "title", "source", "official")} for h in hits]


WINDOW_FRAME = os.path.join(APP_DIR, "window-frame.json")  # Mac: where the window was, so it opens there again
WINDOW_SIZE = (1280, 860)
WINDOW_MIN = (420, 520)


def ns_rect(r):
    """An NSRect as (x, y, width, height)."""
    return (r.origin.x, r.origin.y, r.size.width, r.size.height)


def frame_record(frame, content, screen):
    """What window-frame.json holds, in macOS's global coordinates (origin at the bottom left of the main screen, y
    going up), whole points: the window's frame with its title bar (x, y, width, height), the size of what is inside
    the title bar (width, height: what create_window's width and height mean), and its screen's frame."""
    return {"frame": [round(v) for v in frame], "content": [round(v) for v in content[-2:]],
            "screen": [round(v) for v in screen]}


def restored_geometry(saved, screens):
    """Where to open the window from what window-frame.json saved: {"screen": index into screens, "x", "y" (the
    window's top-left corner from that screen's top left, as pywebview's create_window takes them), "width", "height"
    (inside the title bar, as create_window takes them)}, or None to open it centred as usual. Only when a screen with
    exactly the saved frame is still connected (unplugged or rearranged screens give None). The whole window, title bar
    included, is kept inside that screen's visible frame: below the menu bar and clear of the Dock.
    screens: [(frame, visible frame)], each (x, y, width, height)."""
    try:
        fx, fy, fw, fh = (float(v) for v in saved["frame"])
        cw, ch = (float(v) for v in saved["content"])
        target = [float(v) for v in saved["screen"]]
    except (KeyError, TypeError, ValueError):
        return None
    if len(target) != 4 or min(fw, fh, cw, ch) <= 0 or ch > fh:
        return None
    title = fh - ch  # the title bar's height
    for index, (frame, visible) in enumerate(screens):
        sx, sy, sw, sh = (float(v) for v in frame)
        if [sx, sy, sw, sh] != target:
            continue
        vx, vy, vw, vh = (float(v) for v in visible)
        width = int(min(max(cw, WINDOW_MIN[0]), vw))
        height = int(min(max(ch, WINDOW_MIN[1]), vh - title))
        left = min(max(fx, vx), vx + vw - width)
        top = max(min(fy + fh, vy + vh), vy + height + title)  # the title bar below the menu bar, the bottom above the Dock
        return {"screen": index, "x": int(left - sx), "y": int(sy + sh - top), "width": width, "height": height}
    return None


def native_window(window):
    """The NSWindow behind a pywebview window on a Mac, or None. pywebview has no public way to it."""
    try:
        from webview.platforms.cocoa import BrowserView
        return BrowserView.instances[window.uid].window
    except Exception:  # noqa: BLE001 - another pywebview, or the window is gone
        return None


def mac_screens():
    """Every connected screen's (frame, visible frame), in the order webview.screens lists them (NSScreen.screens())."""
    import AppKit
    return [(ns_rect(s.frame()), ns_rect(s.visibleFrame())) for s in AppKit.NSScreen.screens()]


def save_window_frame(window):
    """Mac: keep where the window is, for the next start. Never raises: a frame that can't be kept costs nothing."""
    if PLATFORM != "darwin":
        return
    try:
        ns = native_window(window)
        screen = ns.screen() if ns is not None else None
        if screen is None:
            return
        frame = ns.frame()
        record = frame_record(ns_rect(frame), ns_rect(ns.contentRectForFrameRect_(frame)), ns_rect(screen.frame()))
        write_private(WINDOW_FRAME, json.dumps(record))
    except Exception as exc:  # noqa: BLE001
        print(f"Couldn't keep the window's place: {exc}", flush=True)


def window_place(webview):
    """Mac: create_window's screen, x, y, width and height for the place the window was closed in, or {} (centred on
    the main screen). Elsewhere {}."""
    if PLATFORM != "darwin":
        return {}
    try:
        with open(WINDOW_FRAME, encoding="utf-8") as f:
            saved = json.load(f)
        screens = webview.screens
        screens = screens() if callable(screens) else screens
        natives = mac_screens()
        if len(natives) != len(screens):
            return {}
        place = restored_geometry(saved, natives)
    except Exception:  # noqa: BLE001 - no file yet, a damaged one, or no screens: open as usual
        return {}
    if not place:
        return {}
    return {"screen": screens[place["screen"]], "x": place["x"], "y": place["y"],
            "width": place["width"], "height": place["height"]}


def open_window(url):
    """Show the app in its own window (macOS's built-in web view) until it is closed. False when pywebview is missing,
    so the caller falls back to the browser."""
    try:
        import webview
    except ImportError:
        return False
    try:
        webview.settings["OPEN_EXTERNAL_LINKS_IN_BROWSER"] = True  # a source's web link goes to the browser
        menu = []
        if PLATFORM == "darwin":  # Settings… (Cmd+,) and Check for Updates… in the app menu, under About, as Mac apps have them
            from webview.menu import Menu, MenuAction
            menu = [Menu("__app__", [MenuAction("Settings…", settings_from_menu), MenuAction("Check for Updates…", check_from_menu)])]
            mac_menu_shortcuts()
        place = {"width": WINDOW_SIZE[0], "height": WINDOW_SIZE[1], **window_place(webview)}
        window = webview.create_window(window_title(), url, min_size=WINDOW_MIN, text_select=True, menu=menu, **place)

        def close_window():  # Quit and Restart now: keep the window's place first, then close it
            save_window_frame(window)
            window.destroy()

        window.events.closing += lambda: save_window_frame(window)  # the window's own close button
        quit_hooks.append(close_window)
        windows.append(window)
        # Windows: Edge's WebView2 only (it comes with Windows 10 22H2 and 11); without it, the browser instead.
        gui = {"gui": "edgechromium"} if PLATFORM == "win32" else {}
        webview.start(private_mode=False, storage_path=os.path.join(APP_DIR, "window"), **gui)
        return True
    except Exception as exc:
        print(f"Couldn't open a window ({exc}); using the browser instead.", flush=True)
        return False


# The menu items call the page with run_js, which runs the script as it is. evaluate_js wraps it in eval(), which the
# page's content security policy (script-src 'self') refuses, so a menu item calling it did nothing.
def menu_to_page(script, what):
    """Bring the window forward (out of the Dock when it was minimised) and run script in the page."""
    for window in windows:
        try:
            window.restore()
            window.show()
            window.run_js(script)
        except Exception as exc:  # noqa: BLE001 - a window still loading: the person can use the page instead
            print(f"{what} couldn't reach the page: {exc}", flush=True)


def settings_from_menu():
    """The app menu's Settings… (Cmd+,): the page opens Settings, as Cmd+, does inside it."""
    menu_to_page("window.SLSettings && window.SLSettings.open()", "Settings…")


def check_from_menu():
    """The app menu's Check for Updates…: the page opens Settings › Status and runs the same check as its button."""
    menu_to_page("window.SLUpdates && window.SLUpdates.fromMenu()", "Check for Updates…")


def mac_menu_shortcuts():
    """Give Settings… its Cmd+, (pywebview's MenuAction takes no shortcut). pywebview builds the app menu again when
    the window first shows and when another window becomes key, so the key is set each time it builds it. A menu key
    works wherever the focus is in the app; the page's own Cmd+, handler only while the page has it."""
    try:
        from AppKit import NSEventModifierFlagCommand
        from webview.platforms.cocoa import BrowserView
    except ImportError:
        return
    if getattr(BrowserView, "_starholm_shortcuts", False):
        return
    build = BrowserView._add_app_menu

    def add_app_menu(self, main_menu, custom_items=None):
        build(self, main_menu, custom_items)
        item = main_menu.itemAtIndex_(0).submenu().itemWithTitle_("Settings…")
        if item is not None:
            item.setKeyEquivalent_(",")
            item.setKeyEquivalentModifierMask_(NSEventModifierFlagCommand)
    BrowserView._add_app_menu = add_app_menu
    BrowserView._starholm_shortcuts = True


