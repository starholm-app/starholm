def executable_path():
    """The path of this process's own executable (for the app, its bundle's Contents/MacOS/ binary), or None."""
    if PLATFORM == "win32":
        return oscompat.own_executable()
    try:
        import ctypes
        size = ctypes.c_uint32(4096)
        buf = ctypes.create_string_buffer(size.value)
        if ctypes.CDLL(None)._NSGetExecutablePath(buf, ctypes.byref(size)) != 0:
            return None
        return os.path.realpath(buf.value.decode("utf-8"))
    except (OSError, AttributeError, UnicodeDecodeError, ValueError):
        return None


def app_bundle():
    """The Starholm.app this server runs inside (ops/make-app.sh's launcher runs Python in the app's own process),
    or None: run from the terminal, by the --script launcher, or anything whose bundle id isn't the app's.
    On Windows: Starholm.exe, the Windows app's launcher (ops/windows-launcher.c), when this process is it."""
    exe = executable_path()
    if PLATFORM == "win32":
        return exe if exe and os.path.basename(exe).lower() == "starholm.exe" else None
    found = re.fullmatch(r"(/.+\.app)/Contents/MacOS/[^/]+", exe or "")
    if not found:
        return None
    try:
        with open(os.path.join(found.group(1), "Contents", "Info.plist"), "rb") as f:
            info = plistlib.loads(f.read(1_000_000))
    except Exception:  # noqa: BLE001 - missing or not a plist: not our app
        return None
    return found.group(1) if isinstance(info, dict) and info.get("CFBundleIdentifier") in APP_BUNDLE_IDS else None


