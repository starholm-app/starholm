def _mac(key, text):
    return hmac.new(key.encode(), text.encode(), hashlib.sha256).hexdigest()


def launch_code(key=None, now=None):
    """A one-time code for /launch: "<unix time>.<16 hex>.<HMAC-SHA256 of both with the launch key>"."""
    stamp, nonce = str(int(time.time() if now is None else now)), secrets.token_hex(8)
    return f"{stamp}.{nonce}.{_mac(key or LAUNCH_KEY, f'launch {stamp} {nonce}')}"


def launch_url(port, key=None, next_path="/"):
    """The address that opens the page on the server at this port, with a fresh launch code."""
    url = f"http://127.0.0.1:{port}/launch?code={launch_code(key)}"
    return url if next_path == "/" else f"{url}&next={quote(next_path, safe='')}"


def use_launch_code(code, now=None):
    """Whether a launch code is this server's, fresh and unused; it is spent either way once it checks out."""
    m = LAUNCH_CODE.fullmatch(code or "")
    if not m:
        return False
    age = (time.time() if now is None else now) - int(m.group(1))
    if not -60 <= age <= LAUNCH_TTL:  # a minute's grace for a clock set back
        return False
    if not hmac.compare_digest(m.group(3), _mac(LAUNCH_KEY, f"launch {m.group(1)} {m.group(2)}")):
        return False
    with launch_lock:
        if code in used_codes:
            return False
        used_codes.add(code)
    return True


def new_session(now=None):
    now = time.time() if now is None else now
    value = secrets.token_urlsafe(32)
    with launch_lock:
        for old in [v for v, ends in sessions.items() if ends <= now]:  # ended ones go when a new one starts
            del sessions[old]
        sessions[value] = now + SESSION_IDLE
    return value


def session_ok(value, now=None):
    """Whether a session cookie value is live; a live one is renewed for another SESSION_IDLE seconds."""
    now = time.time() if now is None else now
    with launch_lock:
        ends = sessions.get(value)
        if ends is None or ends <= now:
            sessions.pop(value, None)
            return False
        sessions[value] = now + SESSION_IDLE
        return True


def cookie_value(header, name):
    """The value of the cookie `name` in a Cookie header, read by hand: pairs split at ";", each at its first "=".
    (http.cookies gives up on the whole header when another site's cookie on 127.0.0.1 holds JSON or quotes.)"""
    for part in (header or "").split(";"):
        key, sep, value = part.partition("=")
        if sep and key.strip() == name:
            return value.strip()
    return None


def session_cookie():
    """The session cookie's name. Cookies don't keep ports apart, so a second copy on another port gets its own."""
