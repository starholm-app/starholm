    def _post(self):
        if not self._allowed():
            self.close_connection = True  # the body stays unread
            return self._send(403, {"error": "forbidden"})
        url = urlparse(self.path)
        if url.path == "/api/myfiles/add":  # the body is the file itself
            return self._add_file(url)
        if url.path in ("/api/maps/print", "/api/maps/download", "/api/maps/pause", "/api/family-plan", "/api/print/pack",
                        "/api/print/plan", "/api/guides/booklet", "/api/guides/booklets"):  # in the upgrade
            if not unlocked():
                self.close_connection = True  # the body stays unread
                return self._send(423, {"error": LOCKED, "locked": True})
        if url.path == "/api/maps/print":  # the body holds the map image, so it has its own cap
            return self._map_print()
        body = self._body()
        model = body.get("model")
        if model is not None and not (isinstance(model, str) and re.fullmatch(r"[\w.:/-]{1,120}", model)):
            raise HTTPProblem(400, "bad model name")
