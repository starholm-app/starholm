def safe_name(name):
    """A file name that is safe to save: no folders, no control or reserved characters."""
    name = re.sub(r'[\x00-\x1f\x7f<>:"/\\|?*]', "_", name.replace("\\", "/").rsplit("/", 1)[-1]).strip(" .")
    stem, ext = os.path.splitext(name)
    ext = ext[:12]
    while len((stem + ext).encode("utf-8")) > 200:  # disks allow 255 bytes; leave room for " (2)"
        stem = stem[:-1]
    return stem.rstrip(" .") + ext if stem.strip(" .") else ""


