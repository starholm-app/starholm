def question_index(chat, start):
    """start from a request, checked against a saved chat: the index of one of its questions, else HTTPProblem 400."""
    if isinstance(start, bool) or not isinstance(start, int):
        raise HTTPProblem(400, "from must be the index of a question in the chat")
    messages = (chat or {}).get("messages") or []
    if not 0 <= start < len(messages) or not isinstance(messages[start], dict) or messages[start].get("role") != "user":
        raise HTTPProblem(400, "from must be the index of a question in the chat")
    return start


def history(chat):
    """A saved chat as messages for the model: what was asked and answered (the lookups aren't kept). A "Documents
    only" question and its list of documents are left out: no model answered it."""
    out = []
    saved = [m for m in (chat or {}).get("messages", []) if isinstance(m, dict)]
    for i, m in enumerate(saved):
        if m.get("documents_only") or (m.get("role") == "user" and i + 1 < len(saved)
                                        and saved[i + 1].get("documents_only")):
            continue
        if m.get("role") in ("user", "assistant") and isinstance(m.get("content"), str):
            # A chat saved before reasoning was caught may hold a draft and a "</think>" line: never send it back.
            content = strip_reasoning(m["content"]) if m["role"] == "assistant" else m["content"]
            out.append({"role": m["role"], "content": content})
    return out


