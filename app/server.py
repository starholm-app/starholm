def quit_on_sigterm():
    """Quit (close the window, stop serving) on SIGTERM. While the window is open the main thread sits in macOS's
    event loop, where a Python signal handler may not run until the next window event, and an exception raised there
    is swallowed: so the signal also wakes a thread through signal.set_wakeup_fd, and that thread quits.
    Not on Windows: nothing sends SIGTERM there, and its wakeup fd must be a socket. Closing the window quits."""
    if PLATFORM == "win32":
        return
    reader, writer = os.pipe()
    os.set_blocking(writer, False)
    signal.set_wakeup_fd(writer, warn_on_full_buffer=False)
    signal.signal(signal.SIGTERM, lambda *_: quit_app())

    def watch():
        while True:
            try:
                data = os.read(reader, 64)
            except OSError:
                return
            if not data:
                return
            if signal.SIGTERM in data:
                quit_app()
    threading.Thread(target=watch, daemon=True, name="sigterm").start()


