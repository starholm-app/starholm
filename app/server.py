class QuietServer(ThreadingHTTPServer):
    daemon_threads = True

    def server_bind(self):
        """HTTPServer.server_bind() also sets server_name with socket.getfqdn(host), a reverse DNS lookup of
        127.0.0.1. On a Mac that lookup is a local network operation: macOS asks "Allow Starholm to find devices on
        local networks?" and blocks the start until the person answers. Nothing reads server_name, so it is set
        without a lookup. Binding and listening on 127.0.0.1 need no permission."""
        socketserver.TCPServer.server_bind(self)
        self.server_name, self.server_port = self.server_address[:2]

    def handle_error(self, request, client_address):
        if isinstance(sys.exc_info()[1], (ConnectionResetError, ConnectionAbortedError, BrokenPipeError)):
            return  # the window closed a connection it kept open; nothing went wrong
        super().handle_error(request, client_address)


def make_server(preferred):
    """Listen on 127.0.0.1 at the preferred port, or any free one if something else holds it."""
    try:
        return QuietServer(("127.0.0.1", preferred), Handler)
    except OSError:
        return QuietServer(("127.0.0.1", 0), Handler)


