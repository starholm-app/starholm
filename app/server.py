def build_time(folder):
    """When the build in folder was made (its build.json "built", an ISO time in UTC), or None."""
    try:
        with open(os.path.join(folder, BUILD_INFO), "rb") as f:
            built = json.loads(f.read(5_000_000).decode("utf-8")).get("built")
    except (OSError, ValueError, UnicodeDecodeError, AttributeError):
        return None
    return built if isinstance(built, str) and parse_time(built) else None


def parse_time(value):
    """An ISO 8601 time as an aware datetime (one without a zone is taken as local time), or None."""
    if not isinstance(value, str) or not value.strip():
        return None
    try:
        moment = datetime.datetime.fromisoformat(value.strip())
    except ValueError:
        return None
    return moment if moment.tzinfo else moment.astimezone()


def newer_library():
    """A newer build the `current` link points at than the one this app started with: {"folder", "built"}, else None.
    Only for the default library (a folder the person picked is never swapped)."""
    if not LIB_IS_DEFAULT:
        return None
    try:
        now = os.path.realpath(search.DEFAULT_LIBRARY)
    except (OSError, AttributeError):
        return None
    if now == os.path.realpath(LIB) or not os.path.isfile(os.path.join(now, "index.sqlite")):
        return None
    return {"folder": now, "built": build_time(now)}


def refresh_state():
    """The weekly refresh, from logs/refresh-status.json: {"known", "running", "started", "finished", "result",
    "changed", "progress"}. A missing file, bad JSON or missing keys give known false (or null fields), never an
    error."""
    out = {"known": False, "running": False, "started": None, "finished": None, "result": None, "changed": [],
           "progress": None}
    try:
        with open(REFRESH_STATUS, "rb") as f:
            raw = json.loads(f.read(1_000_000).decode("utf-8"))
    except (OSError, ValueError, UnicodeDecodeError):
        return out
    if not isinstance(raw, dict):
        return out
    started, finished = parse_time(raw.get("started")), parse_time(raw.get("finished"))
    out.update(known=bool(started or finished),
               started=raw["started"] if started else None, finished=raw["finished"] if finished else None)
    if isinstance(raw.get("result"), str):
        out["result"] = raw["result"][:200]
    changed = raw.get("changed")
    if isinstance(changed, list):
        out["changed"] = [str(c)[:200] for c in changed if isinstance(c, (str, int, float))][:100]
    # refresh.py writes progress as {"step", "text", "source", "done", "total"}; a plain string is accepted too.
    progress = raw.get("progress")
    if isinstance(progress, dict):
        progress = progress.get("text")
    if not isinstance(progress, str):
        progress = next((raw[k] for k in ("doing", "step", "message") if isinstance(raw.get(k), str)), None)
    now = datetime.datetime.now(datetime.timezone.utc)
    out["running"] = bool(started and (not finished or finished < started)
                          and (now - started).total_seconds() < STALE_RUN)
    out["progress"] = progress[:300] if progress and out["running"] else None
    return out


def next_refresh(now=None):
    """When launchd runs the weekly refresh next, as a local ISO time, from the installed LaunchAgent's
    StartCalendarInterval; None when it isn't installed or has no schedule this can read."""
    try:
        with open(REFRESH_PLIST, "rb") as f:
            plist = plistlib.loads(f.read(1_000_000))
    except Exception:  # noqa: BLE001 - missing, unreadable or not a plist
        return None
    if not isinstance(plist, dict):
        return None
    slots = plist.get("StartCalendarInterval")
    slots = slots if isinstance(slots, list) else [slots]
    now = now or datetime.datetime.now().astimezone()
    best = None
    for slot in slots:
        if not isinstance(slot, dict) or not all(isinstance(slot.get(k), int) for k in ("Weekday", "Hour")):
            continue
        weekday = (slot["Weekday"] - 1) % 7  # launchd: 0 and 7 are Sunday; Python: Monday is 0
        minute = slot.get("Minute") if isinstance(slot.get("Minute"), int) else 0
        if not (0 <= slot["Hour"] < 24 and 0 <= minute < 60):
            continue
        day = now + datetime.timedelta(days=(weekday - now.weekday()) % 7)
        when = day.replace(hour=slot["Hour"], minute=minute, second=0, microsecond=0)
        if when <= now:
            when += datetime.timedelta(days=7)
        best = when if best is None or when < best else best
    return best.isoformat(timespec="minutes") if best else None




