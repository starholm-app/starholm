    def _map_print(self):
        """POST /api/maps/print {"title", "subtitle", "scale": {"label", "share"}, "image", "mode": "print"|"pdf"}:
        the area as one A5 page, opened in Preview to print ("print") or saved into Downloads ("pdf")."""
        n = self._length(MAX_MAP_IMAGE + 10_000)
        raw = self.rfile.read(n) if n else b""
        if len(raw) < n:
            self.close_connection = True
            raise HTTPProblem(400, "request cut short")
        try:
            body = json.loads(raw.decode("utf-8"))
        except (ValueError, UnicodeDecodeError):
            raise HTTPProblem(400, "The request isn't valid JSON.") from None
        if not isinstance(body, dict) or body.get("mode") not in ("print", "pdf"):
            raise HTTPProblem(400, "mode must be print or pdf")
        page = map_print_page(body)
        if PLATFORM == "win32":
            raise HTTPProblem(501, PDF_NOT_ON_WINDOWS)
        try:
            path = make_map_printout(page)
        except LookupError:
            raise HTTPProblem(501, "Maps can be printed only in the app's own window.")
        except (RuntimeError, ValueError, OSError) as exc:
            raise HTTPProblem(500, f"Couldn't make the page: {exc}")
        if body["mode"] == "pdf":
            return self._send(200, {"ok": True, "file": save_to_downloads(path, page["title"]), "folder": "Downloads"})
        open_booklet(path, PRINT_DIR)
        return self._send(200, {"ok": True, "file": os.path.basename(path)})

    def _booklet(self, slug, make=None):
        if PLATFORM == "win32":  # the pages are rendered and laid out with macOS's WebKit and Quartz
            raise HTTPProblem(501, PDF_NOT_ON_WINDOWS)
        try:
            return (make or make_booklet)(slug)
        except LookupError:
            raise HTTPProblem(501, "Booklets can be made only in the app's own window.")
        except (RuntimeError, ValueError, OSError) as exc:
            raise HTTPProblem(500, f"Couldn't make the {'booklet' if make in (None, make_booklet) else 'printout'}: {exc}")

    def _guide_figure(self, path):
        """GET /guides/<slug>/<name>.svg: one figure, as image/svg+xml under a policy that lets it run nothing."""
        parts = path[len("/guides/"):].split("/")
        dest = self.headers.get("Sec-Fetch-Dest")
        if dest is not None and dest != "image":  # only an <img> loads a figure; opened on its own it isn't served
            return self._send(404, {"error": "not found"})
        if (len(parts) != 2 or not GUIDE_SLUG.fullmatch(parts[0]) or not GUIDE_FIGURE.fullmatch(parts[1])):
            return self._send(404, {"error": "not found"})
        if guide_locked(parts[0]):
            return self._send(423, {"error": LOCKED, "locked": True})
        full = guide_file(parts[0], parts[1])
        if not full:
            return self._send(404, {"error": "not found"})
        data = read_capped(full)
        self.header_override = {"Content-Security-Policy": FIGURE_CSP}
        return self._send(200, data, "image/svg+xml")

    def _delete(self):
        if not self._allowed():
            return self._send(403, {"error": "forbidden"})
        path = urlparse(self.path).path
        self._body()  # read (and cap) any body, so the connection stays in step
        if path.startswith("/api/chats/"):
            chat_id = path[len("/api/chats/"):]
            if not chat_path(chat_id):
                raise HTTPProblem(400, "bad chat id")
            if not delete_chat(chat_id):
                return self._send(404, {"error": "not found"})
            return self._send(200, {"ok": True})
        return self._send(404, {"error": "not found"})

