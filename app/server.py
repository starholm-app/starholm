def remove_model(model):
    """Remove an installed model through Ollama. Answers then come from model_setup.next_model when it was the model
    in use; with no model left, the chosen model is cleared and the app is in library-only mode. The sentence to
    show."""
    models = chat_models()
    if models is None:
        raise HTTPProblem(503, "Ollama isn't running. Start it first.")
    if model_setup.base(model) not in {model_setup.base(m) for m in models}:
        raise HTTPProblem(400, "That model isn't installed.")
    if PULLS.busy() == model:
        raise HTTPProblem(409, "That model is downloading. Cancel the download first.")
    rows = model_setup.load_rows()
    names = {model_setup.base(r["model"]): r["name"] for r in rows}
    in_use = model_setup.base(model) == model_setup.base(chosen_model() or "")
    then = model_setup.next_model(model, models, rows)
    try:
        model_setup.remove_model(model)
    except (OSError, ValueError) as exc:
        raise HTTPProblem(502, f"Ollama couldn't remove the model: {str(getattr(exc, 'reason', exc))[:200]}") from None
    caps_cache.pop(model, None)
    name = names.get(model_setup.base(model)) or model
    if then is None:
        MEMORY.set_setting("model", None)
        return (f"Removed {name}. No model is left, so questions show the library's documents with no written answer "
                "until you download one.")
    if in_use:
        MEMORY.set_setting("model", then)
        return f"Removed {name}. Answers now come from {names.get(then) or then}."
    return f"Removed {name}."


