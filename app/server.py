    def _save_file(self, url):
        """Save an uploaded file into their folder. ?replace=<name> makes it the new version of that file (the old one
        goes to the Trash); ?keep=1 keeps both when a different file already has this name ("name (2)"); with
        neither, that case answers 409 so the app can ask which they want."""
        self.close_connection = True  # a refused upload leaves its body unread
        size = self._length(myfiles.MAX_FILE_BYTES)
        if files_folder_refusal(MY_DIR):
            raise HTTPProblem(409, files_folder_refusal(MY_DIR))
        query = parse_qs(url.query)
        name = safe_name(query.get("name", [""])[0])
        old = my_file_path(query["replace"][0]) if query.get("replace") else None
        if query.get("replace") and not old:
            raise HTTPProblem(404, "The file you're updating isn't in the folder any more. Add this one instead.")
        if not name or os.path.splitext(name)[1].lower() not in myfiles.KINDS:
            raise HTTPProblem(400, myfiles.CANT_READ)
        if size == 0:
            raise HTTPProblem(400, "This file is empty.")
        os.makedirs(MY_DIR, mode=0o700, exist_ok=True)  # only this user may list their files
        if size + 1e9 > shutil.disk_usage(MY_DIR).free:
            raise HTTPProblem(507, "There isn't enough free disk space for this file.")
        part = os.path.join(MY_DIR, f".{uuid.uuid4().hex}.part")
        try:
            fd = os.open(part, os.O_WRONLY | os.O_CREAT | os.O_EXCL | oscompat.NOFOLLOW | oscompat.BINARY, 0o600)
            with os.fdopen(fd, "wb") as f:
                left = size
                while left:
                    chunk = self.rfile.read(min(left, 1 << 20))
                    if not chunk:
                        raise ConnectionError("upload cut short")
                    f.write(chunk)
                    left -= len(chunk)
            dest = os.path.join(MY_DIR, name)
            if old and os.path.getsize(old) == size and filecmp.cmp(old, part, shallow=False):
                return self._send(200, {"ok": True, "name": my_name(old), "unchanged": True})
            if os.path.lexists(dest) and os.path.realpath(dest) != old:
                if os.path.isfile(dest) and not os.path.islink(dest) and os.path.getsize(dest) == size \
                        and filecmp.cmp(dest, part, shallow=False):
                    return self._send(200, {"ok": True, "name": name, "duplicate": True})  # the same file again
                if not old and query.get("keep", [""])[0] != "1":
                    return self._send(409, {"error": f"You already have a file called {name}.", "name": name})
                stem, ext = os.path.splitext(name)
                n = 2
                while os.path.lexists(dest):
                    dest = os.path.join(MY_DIR, f"{stem} ({n}){ext}")
                    n += 1
            if old:
                try:
                    to_trash(old)
                except Exception:
                    return self._send(500, {"error": "Couldn't move the old version to the Trash."})
            os.replace(part, dest)
        finally:
            if os.path.exists(part):
                os.remove(part)
        check_my_files()
        reply = {"ok": True, "name": my_name(dest)}
        if old:
            reply["replaced"] = my_name(old)
        return self._send(200, reply)

    def _chat(self, body):
        chat_id = body.get("conversation") or uuid.uuid4().hex
        if not chat_path(chat_id):
            raise HTTPProblem(400, "bad conversation id")
        question = body.get("message")
        question = question.strip() if isinstance(question, str) else ""
        if not question:
            raise HTTPProblem(400, "message is required")
        if len(question) > MAX_MESSAGE:
            raise HTTPProblem(400, f"That message is too long (over {MAX_MESSAGE:,} characters).")
        # "reasoning" and "length" (Think harder and the length limit) are gone: answers use the defaults, and an old
        # page that still sends them is not refused.
        settings = answer_settings()
        summarise = body.get("summarise") is True  # Summarise: a model answer, even with Documents only on
        start, replace_one = None, False
        if body.get("from") is not None:  # Edit or Ask again: answer in place of this question and what followed it
            chat = load_chat(chat_id)
            if chat is None:
                raise HTTPProblem(404, "That chat isn't saved.")
            start = question_index(chat, body["from"])
            nxt = chat["messages"][start + 1] if start + 1 < len(chat["messages"]) else None
            # Summarise on a Documents-only question replaces just that question and its documents, in place.
            replace_one = summarise and isinstance(nxt, dict) and nxt.get("documents_only") is True
        if settings["documents_only"] and not summarise:
            return self._documents_only(chat_id, question, start)
        model = body.get("model") or chosen_model()
        if not model:
            raise HTTPProblem(400, "No model chosen. Pick one first.")
        # No model to answer with (no Ollama, Ollama not running, or the model not downloaded): library-only mode, the
        # passages the library finds with one line saying written answers need a model.
        models = chat_models()
        why = no_model_reason(model, models)
        if why:
            if why == "stopped":
                start_ollama()
            return self._documents_only(chat_id, question, start, no_model=why, replace_one=replace_one)
        conv = conversations.setdefault(chat_id, {"model": None, "run": 0})
        caps = model_caps(model)
        if start is not None:  # the chat as it was before that question
            conv.update(model=model, messages=[{"role": "system", "content": prompt_for(caps)}]
                        + history({"messages": chat["messages"][:start]}))
        elif conv.get("model") != model:  # opened from its saved file, new, or the model changed mid-chat
            conv.update(model=model, messages=[{"role": "system", "content": prompt_for(caps)}]
                        + history(load_chat(chat_id)))
        conv["run"] += 1  # a newer question on this chat stops any older one still running
        run = conv["run"]
        messages = conv["messages"]
        keep = len(messages)
        messages.append({"role": "user", "content": question})
        trim(messages)
        self._stream_start()
        lib = library()
        # Searched with the question as typed before the model starts, so the panel has something to read at once.
        # Nothing of it goes to the model: its own searches replace these at the top of the panel's list.
        early = with_refs(lib, documents_for(lib, quick_results(lib, question)))
        events = chat_events(model, lib, messages, caps=caps, memory=MEMORY, mode=settings["mode"],
                             thinking=model.removesuffix(":latest") not in settings["think_off"])
        answered, last_tick, steps = False, 0.0, []  # answered: the answer went out (a memory step may follow it)
        try:
            # The answer mode only when it isn't standard, so a standard answer's events are as they always were (the page
            # reads a chat event with no mode as standard).
            self._event({"type": "chat", "id": chat_id, **({"mode": settings["mode"]} if settings["mode"] != "standard" else {})})
            if early:
                self._event({"type": "documents", "query": question[:MAX_QUERY], "early": True, "documents": early})
            for event in events:
                if conv["run"] != run:
                    break
                if event["type"] == "tick":  # heartbeat: writing it is how we notice a closed or stopped page
                    if time.monotonic() - last_tick > 0.5:
                        last_tick = time.monotonic()
                        self.wfile.write(b": tick\n\n")
                        self.wfile.flush()
                    continue
                if event["type"] in ("search", "read", "show", "think_limit", "retry") \
                        and event.get("why") != "reasoning":  # cleared reasoning isn't a step the page shows
                    steps.append({k: v for k, v in event.items() if k != "results"})
                if event["type"] == "done":  # the sources keep their key and address, so a rebuilt library opens them
                    event = {**event, "sources": with_refs(lib, event.get("sources")),
                             "seen": with_refs(lib, event.get("seen"))}
                self._event(event)
                if event["type"] == "search" and event.get("results"):
                    # The documents it found, with their passages, for the side panel while the answer is written.
                    self._event({"type": "documents", "query": event.get("query", ""),
                                 "documents": with_refs(lib, documents_for(lib, event["results"]))})
                if event["type"] == "done" and conv["run"] == run:
                    answered = True
                    try:
                        self._event({"type": "saved", "chat": record_turn(chat_id, model, question, event, steps,
                                                                           start, replace_one)})
                    except OSError as exc:
                        print(f"Couldn't save chat {chat_id}: {exc}", file=sys.stderr)
                        self._event({"type": "save_failed", "message": "This answer couldn't be saved to the chat's "
                                     "file. Start a new chat to keep a saved copy."})
        except (BrokenPipeError, ConnectionResetError):
            pass  # stopped, or the page was closed
        except Exception as exc:
            try:
                self._event({"type": "error", "message": friendly_error(exc)})
            except OSError:
                pass
        finally:
            events.close()  # closes the request to Ollama, which stops generating
            if not answered and conv["run"] == run:
                del messages[keep:]  # forget the unanswered question so the next one starts clean
                if start is not None:  # the file still has the turns it would have replaced: start from it again
                    conversations.pop(chat_id, None)
            elif replace_one:  # the file has turns after this one that the model's copy lacks: rebuild it next time
                conversations.pop(chat_id, None)

    def _documents_only(self, chat_id, question, start, no_model=None, replace_one=False):
        """"Library only" (the Documents only setting): search the library with the question as typed and send the
        documents found, with their passages, and a done event with no answer. No model runs, and nothing is asked of
        Ollama. The question and its documents are saved to the chat, where the page offers Summarise. no_model: why
        no model could answer (no_model_reason); done then carries it and the line saying answers need a model."""
        lib = library()
        results = quick_results(lib, question)
        documents = with_refs(lib, documents_for(lib, results))
        done = {"type": "done", "answer": "", "documents_only": True, "follow_ups": [], "sources": [], "seen": [],
                "documents": [{k: d.get(k) for k in ("id", "title", "source", "official", "key", "url")}
                              for d in documents],
                "cut_off": False, "unfinished": False, "tokens": 0, "seconds": 0.0}
        if no_model:
            done.update(no_model=no_model, note=NO_MODEL_LINE)
        search_event = {"type": "search", "query": question[:MAX_QUERY], "topic": "any", "results": results}
        self._stream_start()
        try:
            self._event({"type": "chat", "id": chat_id, "documents_only": True,
                         **({"no_model": no_model} if no_model else {})})
            self._event(search_event)
            self._event({"type": "documents", "query": question[:MAX_QUERY], "documents": documents})
            self._event(done)
            try:
                self._event({"type": "saved", "chat": record_turn(
                    chat_id, None, question, done, [{k: v for k, v in search_event.items() if k != "results"}], start,
                    replace_one)})
            except OSError as exc:
                print(f"Couldn't save chat {chat_id}: {exc}", file=sys.stderr)
                self._event({"type": "save_failed", "message": "This search couldn't be saved to the chat's file."})
        except (BrokenPipeError, ConnectionResetError):
            pass
        if start is not None:  # the file lost the turns after it: the model's copy of this chat starts from it again
            conversations.pop(chat_id, None)


