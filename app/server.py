# ---------- stable references to a saved source ----------
# Passage and document ids change when a source is rebuilt, so each saved source also keeps its source key, its
# document's address (url, often empty for Your files) and its title. A saved source is opened by its id only while
# that id still names the same document; otherwise by key and title (and address), at the document's first passage.

def _part(lib, pid):
    """(the index a passage id belongs to, its id there): the library, or Your files above myfiles.ID_OFFSET."""
    if hasattr(lib, "_part"):
        return lib._part(pid)
    return lib, pid


def passage_ref(lib, pid):
    """{"key", "url", "title"} of the document holding a passage, or None."""
    part, local = _part(lib, pid) if lib is not None else (None, 0)
    if part is None or local <= 0:
        return None
    row = part.db.execute("SELECT s.key, d.url, d.title FROM passages p JOIN docs d ON d.id = p.doc_id "
                          "JOIN sources s ON s.id = d.source_id WHERE p.id=?", (local,)).fetchone()
    return {"key": row[0], "url": row[1] or "", "title": row[2]} if row else None


def with_refs(lib, items):
    """Sources or documents with their stable reference (key, url) added."""
    out = []
    for item in items or []:
        ref = passage_ref(lib, item["id"]) if lib is not None and isinstance(item.get("id"), int) else None
        out.append({**item, **({"key": ref["key"], "url": ref["url"]} if ref else {})})
    return out


def resolve_ref(lib, pid, key, url, title):
    """The passage to open for a saved source, never a guess: pid while it still names that document (same source
    key, and the same address, or with no address the same title held by just one document of that source); else the
    first passage of the one document with that key and address; else of the one document with that key and title;
    else None: the document is gone, or more than one could be it."""
    if lib is None:
        return None
    if pid:
        ref = passage_ref(lib, pid)
        if ref and ref["key"] == key and (ref["url"] == url if url else
                                          ref["title"] == title and _same_title(lib, pid, key, title) == 1):
            return pid
    for part, offset in ((getattr(lib, "mine", None), ID_OFFSET), (getattr(lib, "main", lib), 0)):
        if part is None:
            continue
        source = part.db.execute("SELECT id FROM sources WHERE key=?", (key,)).fetchone()
        if not source:
            continue
        docs = part.db.execute("SELECT id FROM docs WHERE source_id=? AND url=? LIMIT 2", (source[0], url)).fetchall() \
            if url else []  # scans only that source's documents: there is no index on the address
        if len(docs) != 1 and title:
            # The index on (source, title) ignores case; the title must still match exactly.
            docs = [(d,) for d, t in part.db.execute("SELECT id, title FROM docs WHERE source_id=? AND title=? "
                                                      "COLLATE NOCASE", (source[0], title)) if t == title]
        if len(docs) != 1:
            return None
        first = part.db.execute("SELECT id FROM passages WHERE doc_id=? ORDER BY id LIMIT 1", (docs[0][0],)).fetchone()
        return first[0] + offset if first else None
    return None


def resolve_by_name(lib, pid, name, title):
    """The passage to open for a source saved before sources kept their key (13 November 2026): only its id, source
    name and title are stored, and the clean-up moved many ids. Never a guess: pid while its document still has that
    source name and that exact title and no other document shares both; else the first passage of the one document
    with that source name and title; else None (gone, or more than one could be it)."""
    if lib is None or not name or not title:
        return None
    matches = []  # (part, offset, doc id) of every document with that source name and title, in both indexes
    for part, offset in ((getattr(lib, "mine", None), ID_OFFSET), (getattr(lib, "main", lib), 0)):
        if part is None:
            continue
        for (source_id,) in part.db.execute("SELECT id FROM sources WHERE label=?", (name,)).fetchall():
            # The index on (source, title) ignores case; the title must still match exactly.
            matches += [(part, offset, d) for d, t in part.db.execute(
                "SELECT id, title FROM docs WHERE source_id=? AND title=? COLLATE NOCASE", (source_id, title)) if t == title]
            if len(matches) > 1:
                return None
    if len(matches) != 1:
        return None
    part, offset, doc_id = matches[0]
    if pid:
        held, local = _part(lib, pid)
        if held is part and local > 0 and part.db.execute("SELECT 1 FROM passages WHERE id=? AND doc_id=?",
                                                          (local, doc_id)).fetchone():
            return pid
    first = part.db.execute("SELECT id FROM passages WHERE doc_id=? ORDER BY id LIMIT 1", (doc_id,)).fetchone()
    return first[0] + offset if first else None


def _same_title(lib, pid, key, title):
    """How many documents of a source share a title (up to 2), in the index pid belongs to."""
    part, _ = _part(lib, pid)
    rows = part.db.execute("SELECT d.title FROM docs d JOIN sources s ON s.id = d.source_id "
                           "WHERE s.key=? AND d.title=? COLLATE NOCASE", (key, title)).fetchall()
    return sum(r[0] == title for r in rows)


def positive_id(value):
    """An article or passage id from a request: a positive integer, else None."""
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        number = value
    elif isinstance(value, str) and re.fullmatch(r"\d{1,15}", value):
        number = int(value)
    else:
        return None
    return number if number > 0 else None


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"
    server_version = "SurvivalLLM"
    sys_version = ""
    header_override = None  # security headers replaced for the next response only (a guide figure's own policy)

    def log_message(self, *args):
        pass

    def end_headers(self):
        extra = getattr(self, "header_override", None) or {}
        for name, value in SECURITY_HEADERS.items():  # on every response, errors included
            self.send_header(name, extra.get(name, value))
        self.header_override = None
        super().end_headers()

    def _allowed(self, need_token=True):
        # The Host check blocks DNS-rebinding pages; the token (a header, never in a URL) blocks other local pages.
        if self.headers.get("Host", "") not in (f"127.0.0.1:{PORT}", f"localhost:{PORT}"):
            return False
        if not need_token:
            return True
        token = self.headers.get("X-Token", "")
        if not token.isascii():  # compare_digest raises on non-ASCII text: that is simply a wrong token
            return False
        return secrets.compare_digest(token, TOKEN)

    def _cross_site(self):
        """Whether the browser says another site made this request: Sec-Fetch-Site cross-site or same-site (another
        port on this computer counts as the same site), or an Origin that isn't this server. Such a request gets 403
        everywhere, so a web page can't tell this app from any other server by loading its files."""
        if self.headers.get("Sec-Fetch-Site", "") in ("cross-site", "same-site"):
            return True
        origin = self.headers.get("Origin")
        return origin is not None and origin not in (f"http://127.0.0.1:{PORT}", f"http://localhost:{PORT}")

    def _has_session(self):
        """Whether the request carries a session cookie that /launch gave out (the page is served only then)."""
        value = cookie_value(self.headers.get("Cookie", ""), session_cookie())
        return bool(value) and session_ok(value)

    def _launch(self, url):
        """GET /launch?code=<launch code>[&next=<path>]: a session cookie and a redirect to the page, or 403."""
        query = parse_qs(url.query)
        code, next_path = query.get("code", [""])[0], query.get("next", ["/"])[0]
        if not LAUNCH_NEXT.fullmatch(next_path):
            return self._send(403, SIGN_IN_PAGE, "text/html; charset=utf-8")
        if not use_launch_code(code):
            if self._has_session():  # a spent code reloaded, or opened again, by a window that is already in
                self.send_response(303)
                self.send_header("Location", next_path)
                self.send_header("Content-Length", "0")
                self.end_headers()
                return None
            return self._send(403, SIGN_IN_PAGE, "text/html; charset=utf-8")
        self.send_response(303)
        self.send_header("Location", next_path)
        self.send_header("Set-Cookie", f"{session_cookie()}={new_session()}; Path=/; HttpOnly; SameSite=Strict")
        self.send_header("Content-Length", "0")
        self.end_headers()
        return None

    def _send(self, code, body, ctype="application/json"):
        data = body if isinstance(body, bytes) else json.dumps(body).encode()
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def _stream_start(self):
        self.send_response(200)
        self.send_header("Content-Type", "text/event-stream")
        self.send_header("Connection", "close")
        self.end_headers()
        self.close_connection = True

    def _event(self, event):
        self.wfile.write(b"data: " + json.dumps(event).encode() + b"\n\n")
        self.wfile.flush()

    def _length(self, cap):
        """The request's Content-Length, refused when missing for a body, malformed or over cap."""
        if self.headers.get("Transfer-Encoding"):
            self.close_connection = True
            raise HTTPProblem(411, "Send the body with a Content-Length.")
        raw = self.headers.get("Content-Length") or "0"
        if not re.fullmatch(r"\d{1,12}", raw.strip()):
            self.close_connection = True
            raise HTTPProblem(400, "bad Content-Length")
        n = int(raw)
        if n > cap:
            self.close_connection = True  # the body stays unread
            raise HTTPProblem(413, "That request is too big.")
        return n

    def _body(self):
        """The JSON object sent with a request ({} when there is none)."""
        n = self._length(MAX_BODY)
        raw = self.rfile.read(n) if n else b""
        if len(raw) < n:
            self.close_connection = True
            raise HTTPProblem(400, "request cut short")
        try:
            body = json.loads(raw.decode("utf-8")) if raw.strip() else {}
        except (ValueError, UnicodeDecodeError):
            raise HTTPProblem(400, "The request isn't valid JSON.") from None
        if not isinstance(body, dict):
            raise HTTPProblem(400, "The request must be a JSON object.")
        return body

    def _dispatch(self, method):
        try:
            return method()
        except HTTPProblem as problem:
            return self._send(problem.code, {"error": problem.message, **problem.extra})
        except (BrokenPipeError, ConnectionResetError):
            return None

    def do_GET(self):
        return self._dispatch(self._get)

    def do_POST(self):
        return self._dispatch(self._post)

    def do_DELETE(self):
        return self._dispatch(self._delete)

