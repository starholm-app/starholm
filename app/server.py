def check_pref(key, value):
    """One preference from a request, checked (widths snap to 20 px steps); HTTPProblem 400 when it isn't valid."""
    if key == "theme":
        if value not in THEMES:
            raise HTTPProblem(400, "theme must be one of: system, light, dark")
        return value
    if key == "sidebar_hidden":
        if not isinstance(value, bool):
            raise HTTPProblem(400, "sidebar_hidden must be true or false")
        return value
    if key in PREF_RANGES:
        low, high, step = PREF_RANGES[key]
        if isinstance(value, bool) or not isinstance(value, (int, float)) or not low <= value <= high:
            raise HTTPProblem(400, f"{key} must be a number from {low} to {high}")
        return min(high, max(low, int(round(value / step)) * step))
    raise HTTPProblem(400, f"unknown preference: {str(key)[:40]}")


