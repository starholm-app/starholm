def map_print_page(body):
    """The checked page a map printout shows: {"title", "subtitle", "scale", "image"}; HTTPProblem 400 otherwise."""
    image = body.get("image")
    if not isinstance(image, str) or len(image) > MAX_MAP_IMAGE or not MAP_IMAGE.fullmatch(image):
        raise HTTPProblem(400, "The map image is missing or too big.")
    scale = body.get("scale") if isinstance(body.get("scale"), dict) else {}
    label, share = scale.get("label"), scale.get("share")
