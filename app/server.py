def render_page_pdf(next_path, out_pdf, timeout=120):
    """Print a print page (next_path, one LAUNCH_NEXT allows) to an A5 PDF at out_pdf, as render_guide_pdf does."""
    if not LAUNCH_NEXT.fullmatch(next_path) or next_path == "/":
        raise ValueError("not a print page")
    if not windows:
        raise LookupError("no window")
    import AppKit
    import Foundation
    import WebKit
    from PyObjCTools import AppHelper
    # Its own launch code: this web view has its own cookies, so it signs in like a window of its own.
    url = launch_url(PORT, next_path=next_path)
    done = threading.Event()
    state = {"error": None}
    keep = {}
    started = time.time()

    def finish(error=None):
        state["error"] = error
        win = keep.pop("win", None)
        keep.pop("wv", None)
        keep.pop("delegate", None)
        if win is not None:
            AppHelper.callAfter(win.close)  # AppKit windows close on the main thread only
        done.set()

    def start():
        try:
            win = AppKit.NSWindow.alloc().initWithContentRect_styleMask_backing_defer_(
                Foundation.NSMakeRect(-30000, -30000, 600, 850), AppKit.NSWindowStyleMaskBorderless,
                AppKit.NSBackingStoreBuffered, False)
            win.setReleasedWhenClosed_(False)
            wv = WebKit.WKWebView.alloc().initWithFrame_configuration_(Foundation.NSMakeRect(0, 0, 600, 850),
                                                                      WebKit.WKWebViewConfiguration.alloc().init())
            win.setContentView_(wv)
            keep.update(win=win, wv=wv)
            wv.loadRequest_(Foundation.NSURLRequest.requestWithURL_(Foundation.NSURL.URLWithString_(url)))
            AppHelper.callLater(0.3, poll)
        except Exception as exc:  # noqa: BLE001  (reported to the page as a failure)
            finish(f"couldn't start: {exc}")

    def poll():
        if "wv" not in keep:
            return
        if time.time() - started > timeout:
            return finish("timed out")

        def got(result, error):
            if result == "1":
                AppHelper.callAfter(print_now)
            elif result == "error":
                finish("the page didn't render")
            else:
                AppHelper.callLater(0.3, poll)
        keep["wv"].evaluateJavaScript_completionHandler_("document.documentElement.dataset.printReady || ''", got)

    def print_now():
        try:
            info = AppKit.NSPrintInfo.sharedPrintInfo().copy()
            info.setJobDisposition_(AppKit.NSPrintSaveJob)
            info.dictionary()[AppKit.NSPrintJobSavingURL] = Foundation.NSURL.fileURLWithPath_(out_pdf)
            info.setPaperSize_(Foundation.NSMakeSize(*A5))
            info.setOrientation_(AppKit.NSPaperOrientationPortrait)
            for side in ("Top", "Bottom", "Left", "Right"):
                getattr(info, f"set{side}Margin_")(0)  # the print stylesheet's @page margins do the work
            info.setHorizontalPagination_(AppKit.NSPrintingPaginationModeFit)
            info.setVerticalPagination_(AppKit.NSPrintingPaginationModeAutomatic)
            op = keep["wv"].printOperationWithPrintInfo_(info)
            op.setShowsPrintPanel_(False)
            op.setShowsProgressPanel_(False)
            op.view().setFrame_(Foundation.NSMakeRect(0, 0, A5[0], A5[1]))
            # Asynchronous, as pywebview's own Print is: a synchronous runOperation() blocks the main thread that the
            # web view needs in order to draw its pages.
            delegate = _print_delegate()(lambda ok: finish(None if ok and os.path.isfile(out_pdf) else "printing failed"))
            keep["delegate"] = delegate
            op.runOperationModalForWindow_delegate_didRunSelector_contextInfo_(
                keep["win"], delegate, b"printOperationDidRun:success:contextInfo:", None)
        except Exception as exc:  # noqa: BLE001
            finish(f"printing failed: {exc}")

    AppHelper.callAfter(start)
    if not done.wait(timeout + 30):
        raise RuntimeError("the booklet took too long")
    if state["error"]:
        raise RuntimeError(state["error"])


_PRINT_DELEGATE = []


def _print_delegate():
    """A small Objective-C class whose printOperationDidRun:success:contextInfo: calls back into Python (made once)."""
    if not _PRINT_DELEGATE:
        import objc
        from Foundation import NSObject

        class BookletPrintDelegate(NSObject):
            def initWithCallback_(self, callback):
                self = objc.super(BookletPrintDelegate, self).init()
                if self is not None:
                    self.callback = callback
                return self

            @objc.typedSelector(b"v@:@Z^v")
            def printOperationDidRun_success_contextInfo_(self, op, success, context):
                self.callback(bool(success))

        _PRINT_DELEGATE.append(lambda callback: BookletPrintDelegate.alloc().initWithCallback_(callback))
    return _PRINT_DELEGATE[0]


