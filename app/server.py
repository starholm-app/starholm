def unsafe_mode(path):
    """Whether someone other than the owner could change this file or folder (writable by group or others), or it
    can't be checked."""
    try:
        return bool(os.stat(path).st_mode & 0o022)
    except OSError:
        return True


def path_candidates(search_path=None):
    """Where PATH says to look for ollama: absolute folders only, none inside this checkout, and none where the folder
    or an ollama already in it is writable by group or others (another account could swap in its own program)."""
    if PLATFORM == "win32":  # file modes can't show who may write there: only Ollama's own install folder counts
        return ()
    search_path = os.environ.get("PATH", "") if search_path is None else search_path
    here = os.path.realpath(ROOT)
    out = []
    for folder in search_path.split(os.pathsep):
        if not folder or not os.path.isabs(folder):
            continue
        real = os.path.realpath(folder)
        if real == here or real.startswith(here + os.sep) or unsafe_mode(folder):
            continue
        binary = os.path.join(folder, "ollama")
        if os.path.lexists(binary) and unsafe_mode(binary):
            continue
        out.append(binary)
    return tuple(out)


def find_ollama(candidates=OLLAMA_CANDIDATES, search_path=None):
    """The first executable file among the candidates, then on PATH; the first candidate when there is none (so "not
    installed" reads the same)."""
    for path in tuple(candidates) + path_candidates(search_path):
        if os.path.isfile(path) and os.access(path, os.X_OK):
            return path
    return candidates[0]


