def _make_guide_pdf(slug, folder, finish):
    """Render the guide to A5 pages, then finish(pages, out) lays them out into folder/<slug>-<hash>.pdf."""
    with _booklet_lock:
        private_dir(folder)
        path = booklet_path(slug, folder)
        if os.path.isfile(path):
            return path
        pages = os.path.join(folder, f".{slug}-pages.pdf")
        part = path + ".part"
        try:
            render_guide_pdf(slug, pages)
            finish(pages, part)
            os.replace(part, path)
        finally:
            for leftover in (pages, part):
                if os.path.exists(leftover):
                    os.remove(leftover)
        for name in os.listdir(folder):
            old = os.path.join(folder, name)
            if name.startswith(f"{slug}-") and name.endswith(".pdf") and old != path and re.fullmatch(rf"{re.escape(slug)}-[0-9a-f]{{12}}\.pdf", name):
                os.remove(old)
        return path



