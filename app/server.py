def warm_model(model):
    """Load an installed model into memory ahead of the first question, so that question isn't slow."""
    if warming.get(model) == "loading" or model.removesuffix(":latest") in loaded_models():
        return

    def run():
        warming[model] = "loading"
        try:
            # The same num_ctx as every chat request: without it Ollama loads the model at its default context
            # (262,144 tokens, about 25 GB), and the first question then makes it load the model again.
            with ollama_request("/api/generate", {"model": model, "keep_alive": "15m",
                                                  "options": {"num_ctx": NUM_CTX}}, timeout=600) as resp:
                resp.read()
            warming.pop(model, None)
        except OSError:
            warming[model] = "error"
    threading.Thread(target=run, daemon=True).start()


def friendly_error(exc):
    """Plain-language explanation of an Ollama failure."""
    if isinstance(exc, urllib.error.HTTPError):
        try:
            detail = str(json.loads(exc.read().decode("utf-8", "replace")).get("error", ""))
        except (ValueError, OSError, AttributeError):
            detail = ""
        low = detail.lower()
        if exc.code == 404 or "not found" in low:
            return ("This model isn't installed. Pick another one, or install it from the terminal with "
                    "`ollama pull`.")
        if "newer version" in low or "requires" in low and "ollama" in low:
            return ollama_install.upgrade_hint(OLLAMA_BIN)  # brew upgrade only for Homebrew's Ollama
        if "memory" in low:
            return "There isn't enough free memory for this model. Close other apps, or pick a smaller model."
        return f"The AI engine reported a problem: {detail or exc.reason}."
    if getattr(exc, "errno", None) == errno.ENOSPC:
        return "The disk is full. Free up some space, then try again."
    reason = getattr(exc, "reason", exc)
    if isinstance(reason, ConnectionRefusedError) or "refused" in str(reason).lower():
        start_ollama()
        return "The AI engine (Ollama) isn't running. Starting it now; try again in a few seconds."
    if "timed out" in str(reason).lower():
        return "The AI engine took too long to answer. Try again, or pick a faster model."
    return f"Something went wrong: {exc}"


