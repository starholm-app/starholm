def shown_path(path):
    """A path as the page shows it: the home folder written as ~ (~/Library/Application Support/Starholm), so a screen
    or a screenshot never carries the person's account name. Anything outside the home folder is shown as it is."""
    text = str(path or "")
    home = os.path.expanduser("~").rstrip("\\/")
    if home and text and (os.path.normcase(text) == os.path.normcase(home)
                          or os.path.normcase(text).startswith(os.path.normcase(home) + os.sep)):
        return "~" + text[len(home):]
    return text


def save_failed(exc, path):
    """What to tell the person when the memory or settings file couldn't be written."""
    print(f"Couldn't save {path}: {exc}", file=sys.stderr)
    if getattr(exc, "errno", None) == errno.ENOSPC:
        return "Couldn't save: the disk is full. Free some space and try again."
    return f"Couldn't save {shown_path(path)}: {getattr(exc, 'strerror', None) or exc}."


# ---------- saved chats ----------

CHAT_ID = re.compile(r"[0-9a-f]{32}")
MAX_CHAT_BYTES = 20 * 1024 ** 2
_CONTROL = re.compile(r"[\x00-\x1f\x7f-\x9f]")


def chat_path(chat_id):
    """The file of a chat, or None for an id that isn't 32 lowercase hex digits (so no id can leave the folder)."""
    if not isinstance(chat_id, str) or not CHAT_ID.fullmatch(chat_id):
        return None
    return os.path.join(CHATS_DIR, chat_id + ".json")


def clean_title(text):
    return " ".join(_CONTROL.sub(" ", str(text)).split())[:MAX_TITLE].strip()


def load_chat(chat_id):
    """A saved chat as a dict, or None when there is none (or it isn't a readable chat file)."""
    path = chat_path(chat_id)
    if not path:
        return None
    try:
        fd = os.open(path, os.O_RDONLY | oscompat.NOFOLLOW | oscompat.BINARY)
    except OSError:
        return None
    try:
        with os.fdopen(fd, "rb") as f:
            st = os.fstat(f.fileno())
            if not stat.S_ISREG(st.st_mode) or st.st_size > MAX_CHAT_BYTES:
                return None
            chat = json.loads(f.read().decode("utf-8"))
    except (OSError, ValueError):
        return None
    if not isinstance(chat, dict) or chat.get("id") != chat_id or not isinstance(chat.get("messages"), list):
        return None
    return chat


def chat_summary(chat):
    return {"id": chat["id"], "title": chat.get("title") or "New chat", "created": chat.get("created"),
            "updated": chat.get("updated"), "model": chat.get("model"), "messages": len(chat["messages"])}


def list_chats():
    """Every saved chat's summary, the most recently updated first."""
    chats = []
    try:
        entries = list(os.scandir(CHATS_DIR))
    except OSError:
        return []
    for entry in entries:
        chat_id = entry.name[:-5] if entry.name.endswith(".json") else ""
        if CHAT_ID.fullmatch(chat_id) and entry.is_file(follow_symlinks=False):
            chat = load_chat(chat_id)
            if chat:
                chats.append(chat_summary(chat))
    return sorted(chats, key=lambda c: c.get("updated") or 0, reverse=True)


def save_chat(chat):
    private_dir(CHATS_DIR)
    write_private(chat_path(chat["id"]), json.dumps(chat, ensure_ascii=False))


class ChatFileUnreadable(OSError):
    """A chat file is there but can't be read back (too big, damaged, a symlink): it is never saved over."""


# What an answer saves beyond its text, when the done event has it: the statement marks and checked claims of a quoted
# answer mode, how well the model kept the marker format, and the documents a "Documents only" question found.
SAVED_EXTRAS = ("marked", "claims", "grounding", "no_match", "no_match_call", "emergency_call", "documents_only",
                "no_model", "documents")


def record_turn(chat_id, model, question, done, steps, start=None, replace_one=False):
    """Add one answered question to the chat's file (made on its first answer). Returns the chat's summary. start: the
    index of a question in the chat's messages; it and everything after it are dropped first (Edit and Ask again),
    or, with replace_one (Summarise on a "Documents only" question), just it and its answer, in place.
    Raises ChatFileUnreadable, leaving the file alone, when a file for this chat exists but isn't a readable chat."""
    now = time.time()
    with chat_lock:
        chat = load_chat(chat_id)
        if chat is None and os.path.lexists(chat_path(chat_id)):
            raise ChatFileUnreadable(f"{shown_path(chat_path(chat_id))} is too big, damaged or not a plain file; it was kept as it is")
        chat = chat or {"id": chat_id, "title": "", "title_set": False, "created": now, "messages": []}
        at = None
        if start is not None and replace_one:
            del chat["messages"][start:start + 2]
            at = start
        elif start is not None:
            del chat["messages"][start:]
        if not chat.get("title_set") and not any(m.get("role") == "user" for m in chat["messages"]
                                                 if isinstance(m, dict)):
            chat["title"] = clean_title(question) or "New chat"
        turn = [{"role": "user", "content": question, "at": now},
                {"role": "assistant", "content": done.get("answer") or "", "at": now,
                 "sources": done.get("sources") or [], "steps": steps,
                 "follow_ups": done.get("follow_ups") or [],
                 "cut_off": bool(done.get("cut_off")), "unfinished": bool(done.get("unfinished")),
                 **{k: done[k] for k in SAVED_EXTRAS if done.get(k) is not None}}]
        chat["messages"][len(chat["messages"]) if at is None else at:at] = turn
        chat.update(updated=now, **({"model": model} if model else {}))  # a Documents-only search used no model
        save_chat(chat)
    return chat_summary(chat)


