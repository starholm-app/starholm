def booklet_order(n, blanks=False):
    """The sides of a saddle-stitched booklet of n pages: [(left, right), …], front then back of each sheet in turn,
    pages numbered from 1. The page count is padded to a multiple of four (at least four); a padded page is 0, or its
    number in the booklet with blanks=True. Print double-sided flipping on the short edge, keep the sheets in the
    order they print with the first sheet's front (the last page and page 1) facing out, fold the stack in half, and
    the pages read 1, 2, 3, … The first sheet is the outermost: its front holds the back cover and page 1."""
    total = max(4, -(-int(n) // 4) * 4)
    sides = []
    for s in range(total // 4):
        sides.append((total - 2 * s, 2 * s + 1))
        sides.append((2 * s + 2, total - 2 * s - 1))
    return sides if blanks else [tuple(p if p <= n else 0 for p in side) for side in sides]


# The foot of every printed page: its number in the bottom outside corner (odd, right-hand pages on the right, even,
# left-hand pages on the left, as in a book) and the app's name, smaller and lighter, centred on the same line. Both sit
# inside the print stylesheet's 16 mm bottom margin, below the text, and the number lines up with its 12 mm side margin.
PAGE_NUMBER_SIZE = 9   # points
PAGE_NUMBER_GREY = 0.35  # 0 is black, 1 white: a mid grey that prints lightly
PAGE_NAME = b"Starholm"
PAGE_NAME_SIZE = 6.5   # points, smaller than the number
PAGE_NAME_GREY = 0.55  # lighter than the number
PAGE_NAME_SPACING = 0.5  # points between letters
PAGE_NUMBER_FOOT = 20  # points from the page's bottom edge to the baseline (the bottom margin is 16 mm, 45 points)
PAGE_NUMBER_SIDE = 34  # points from the page's outside edge to the number (the side margins are 12 mm, 34 points)


def _text_width(text, size, spacing):
    """The width of text in Helvetica at size, in points, measured by drawing it unseen into a scratch bitmap (drawn
    unseen into the PDF itself, it would still be there as text)."""
    import Quartz
    scratch = Quartz.CGBitmapContextCreate(None, 1, 1, 8, 0, Quartz.CGColorSpaceCreateDeviceGray(), 0)
    Quartz.CGContextSelectFont(scratch, b"Helvetica", size, Quartz.kCGEncodingMacRoman)
    Quartz.CGContextSetCharacterSpacing(scratch, spacing)
    Quartz.CGContextSetTextMatrix(scratch, Quartz.CGAffineTransformIdentity)
    Quartz.CGContextSetTextDrawingMode(scratch, Quartz.kCGTextInvisible)
    Quartz.CGContextSetTextPosition(scratch, 0, 0)
    Quartz.CGContextShowText(scratch, text, len(text))
    return Quartz.CGContextGetTextPosition(scratch).x - spacing  # no space after the last letter


def _show_text(ctx, text, size, grey, spacing, place):
    """Draw text in Helvetica at size in grey; place(width) gives the x of its left end from its measured width."""
    import Quartz
    width = _text_width(text, size, spacing)
    Quartz.CGContextSaveGState(ctx)
    Quartz.CGContextSelectFont(ctx, b"Helvetica", size, Quartz.kCGEncodingMacRoman)
    Quartz.CGContextSetCharacterSpacing(ctx, spacing)
    Quartz.CGContextSetTextMatrix(ctx, Quartz.CGAffineTransformIdentity)
    Quartz.CGContextSetTextDrawingMode(ctx, Quartz.kCGTextFill)
    Quartz.CGContextSetGrayFillColor(ctx, grey, 1.0)
    x, y = place(width)
    Quartz.CGContextShowTextAtPoint(ctx, x, y, text, len(text))
    Quartz.CGContextRestoreGState(ctx)


def draw_page_foot(ctx, number, x, y, width, scale=1.0):
    """The foot of a page whose bottom-left corner is (x, y) and whose width is width: its number in the outside corner
    (odd on the right, even on the left) and the app's name centred, both in light grey. scale: the page's scale on
    the sheet, so the foot shrinks with the page. For a booklet, number is the page's number in the booklet, so once
    folded every number sits on the booklet's outer edge."""
    number = int(number)
    base, side = y + PAGE_NUMBER_FOOT * scale, PAGE_NUMBER_SIDE * scale
    _show_text(ctx, PAGE_NAME, PAGE_NAME_SIZE * scale, PAGE_NAME_GREY, PAGE_NAME_SPACING * scale,
               lambda w: (x + (width - w) / 2, base))
    _show_text(ctx, str(number).encode(), PAGE_NUMBER_SIZE * scale, PAGE_NUMBER_GREY, 0,
               lambda w: (x + width - side - w if number % 2 else x + side, base))


def impose_booklet(src, dst, sheet=A4_LANDSCAPE):
    """Lay the pages of the PDF at src two to a side of an A4 landscape sheet, in booklet_order, into a new PDF at dst.
    Each page is scaled to fit its half and centred; a padded page is left blank. Returns the number of sides written.
    Uses Quartz (pyobjc, part of pywebview's macOS dependencies)."""
    import Quartz
    from Foundation import NSURL
    doc = Quartz.CGPDFDocumentCreateWithURL(NSURL.fileURLWithPath_(src))
    if doc is None:
        raise ValueError("not a PDF")
    n = Quartz.CGPDFDocumentGetNumberOfPages(doc)
    if n < 1:
        raise ValueError("a PDF with no pages")
    w, h = sheet
    media = Quartz.CGRectMake(0, 0, w, h)
    ctx = Quartz.CGPDFContextCreateWithURL(NSURL.fileURLWithPath_(dst), media, None)
    if ctx is None:
        raise OSError("couldn't write the booklet")
    sides = booklet_order(n)
    first = Quartz.CGPDFPageGetBoxRect(Quartz.CGPDFDocumentGetPage(doc, 1), Quartz.kCGPDFCropBox)
    for side, numbers in zip(sides, booklet_order(n, blanks=True)):
        Quartz.CGPDFContextBeginPage(ctx, None)
        for slot, (number, label) in enumerate(zip(side, numbers)):
            page = Quartz.CGPDFDocumentGetPage(doc, number) if number else None
            box = Quartz.CGPDFPageGetBoxRect(page, Quartz.kCGPDFCropBox) if page else first
            bw, bh = box.size.width, box.size.height
            scale = min((w / 2) / bw, h / bh)
            x0, y0 = slot * w / 2 + (w / 2 - bw * scale) / 2, (h - bh * scale) / 2
            if page:
                Quartz.CGContextSaveGState(ctx)
                Quartz.CGContextTranslateCTM(ctx, x0, y0)
                Quartz.CGContextScaleCTM(ctx, scale, scale)
                Quartz.CGContextTranslateCTM(ctx, -box.origin.x, -box.origin.y)
                Quartz.CGContextClipToRect(ctx, box)
                Quartz.CGContextDrawPDFPage(ctx, page)
                Quartz.CGContextRestoreGState(ctx)
            draw_page_foot(ctx, label, x0, y0, bw * scale, scale)  # blanks too, so the folded booklet counts on
        Quartz.CGPDFContextEndPage(ctx)
    Quartz.CGPDFContextClose(ctx)
    return len(sides)


def number_pages(src, dst):
    """Copy the PDF at src to dst, each page as it is with its foot drawn on (draw_page_foot: 1, 2, 3, … in the outside
    corner, and the app's name): the printout of the Print button. Returns the number of pages. ValueError when src isn't a PDF with pages."""
    import Quartz
    from Foundation import NSURL
    doc = Quartz.CGPDFDocumentCreateWithURL(NSURL.fileURLWithPath_(src))
    if doc is None:
        raise ValueError("not a PDF")
    n = Quartz.CGPDFDocumentGetNumberOfPages(doc)
    if n < 1:
        raise ValueError("a PDF with no pages")
    first = Quartz.CGPDFPageGetBoxRect(Quartz.CGPDFDocumentGetPage(doc, 1), Quartz.kCGPDFMediaBox)
    media = Quartz.CGRectMake(0, 0, first.size.width, first.size.height)  # the renderer makes every page one size
    ctx = Quartz.CGPDFContextCreateWithURL(NSURL.fileURLWithPath_(dst), media, None)
    if ctx is None:
        raise OSError("couldn't write the printout")
    for i in range(1, n + 1):
        page = Quartz.CGPDFDocumentGetPage(doc, i)
        box = Quartz.CGPDFPageGetBoxRect(page, Quartz.kCGPDFMediaBox)
        Quartz.CGPDFContextBeginPage(ctx, None)
        Quartz.CGContextSaveGState(ctx)
        Quartz.CGContextTranslateCTM(ctx, -box.origin.x, -box.origin.y)
        Quartz.CGContextDrawPDFPage(ctx, page)
        Quartz.CGContextRestoreGState(ctx)
        draw_page_foot(ctx, i, 0, 0, first.size.width)
        Quartz.CGPDFContextEndPage(ctx)
    Quartz.CGPDFContextClose(ctx)
    return n


