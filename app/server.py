ANSWER_DEFAULTS = {"documents_only": False, "mode": "fetch-quoted", "think_off": []}  # fetch-quoted chosen 14 November 2026
MODEL_NAME = re.compile(r"[\w.:/-]{1,120}")


def answer_settings():
    """{"documents_only": bool, "mode": one of core.ANSWER_MODES, "think_off": [models]}, defaults for anything not
    saved or not valid. documents_only: a question shows the documents found, and no model runs until Summarise.
    mode: how answers are grounded (core.py, "grounded answers"). think_off: models that answer with no reasoning."""
    saved = MEMORY._settings().get("answers")
    saved = saved if isinstance(saved, dict) else {}
    out = {k: (list(v) if isinstance(v, list) else v) for k, v in ANSWER_DEFAULTS.items()}
    if isinstance(saved.get("documents_only"), bool):
        out["documents_only"] = saved["documents_only"]
    if saved.get("mode") in ANSWER_MODES:
        out["mode"] = saved["mode"]
    if isinstance(saved.get("think_off"), list):
        out["think_off"] = [m for m in saved["think_off"] if isinstance(m, str) and MODEL_NAME.fullmatch(m)][:20]
    return out


def check_answer_settings(body):
    """The answer settings a request changes, checked; HTTPProblem 400 when one isn't valid."""
    known = {}
    for key, value in body.items():
        if key == "documents_only":
            if not isinstance(value, bool):
                raise HTTPProblem(400, "documents_only must be true or false")
        elif key == "mode":
            if value not in ANSWER_MODES:
                raise HTTPProblem(400, f"mode must be one of: {', '.join(ANSWER_MODES)}")
        elif key == "think_off":
            if not isinstance(value, list) or len(value) > 20 or not all(
                    isinstance(m, str) and MODEL_NAME.fullmatch(m) for m in value):
                raise HTTPProblem(400, "think_off must be a list of model names")
            value = sorted(set(value))
        else:
            raise HTTPProblem(400, f"unknown answer setting: {str(key)[:40]}")
        known[key] = value
    if not known:
        raise HTTPProblem(400, "Send at least one setting.")
    return known


