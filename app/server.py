def library_overlap(folder):
    """Why folder can't be Your files because of the library, or None: it is the library or inside it (a refresh
    replaces it), or it holds the library (its articles would count as their files). Compared by identity."""
    try:
        mine, library_lineage = _lineage(folder), _lineage(LIB)
    except OSError:
        return None  # no library there, or no such folder
    if library_lineage[0] in mine:
        return "That's inside the library folder, which a library refresh replaces. Pick another folder."
    if mine[0] in library_lineage:
        return ("That folder holds the library, so its articles would count as your files. Pick a folder inside it, "
                "or another one.")
    return None


