# ---------- opening the window: launch codes and sessions ----------
# The page carries the token, so only a window this user opened may load it. Every account on the computer can reach
# 127.0.0.1, but only this user can read app-data/server.json (600, in a 700 folder), which holds LAUNCH_KEY. A launch
# code is made from that key: /launch?code=<code> works once, within LAUNCH_TTL seconds, and answers with a session
# cookie and a redirect to the page. The page itself (index.html, print.html) is served only with that cookie. A session
# ends after SESSION_IDLE seconds without use: a browser sends the cookie to every port on 127.0.0.1, so in browser
# mode another local server the person visits could see it, and a forgotten session shouldn't work for ever.
LAUNCH_KEY = secrets.token_hex(32)
LAUNCH_TTL = 600  # seconds a launch code works for
SESSION_IDLE = 12 * 3600  # seconds a session lasts without use; each use renews it
LAUNCH_CODE = re.compile(r"([0-9]{1,12})\.([0-9a-f]{16})\.([0-9a-f]{64})")
# Where /launch may send the window: the app, or the print page (render_page_pdf) for one guide, the country card's
# numbers, the emergency pack, the family plan or one library document (by any of its passage ids).
LAUNCH_NEXT = re.compile(r"/(?:static/print\.html\?(?:guide=[a-z0-9-]{1,80}|numbers=1|pack=1|plan=1|map=1|passage=[0-9]{1,15}))?")
CHALLENGE = re.compile(r"[0-9a-f]{16,64}")
